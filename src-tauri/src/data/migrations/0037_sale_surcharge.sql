-- طلب صاحب المحل (2026-11-09): «أقدر أضيف فلوس على السعر النهائي» وقت البيع.
--
-- الزيادة مش خصم: الخصم بينزل من البنود، والزيادة بتطلع فوق إجمالي البنود
-- (توصيل، خدمة، تركيب، تقريب). فما ينفعش تتكتب كخصم سالب — الجدول بيرفض
-- `discount_minor < 0` عن حق — ولا كصنف وهمي في المخزن.
--
-- فقرة مستقلة في مستند البيع:
--   total_minor = (إجمالي البنود − الخصم) + surcharge_minor
--
-- `discount_minor` يفضل معناه الوحيد: اللي نزل من البنود. ولذلك التقارير اللي
-- بتقرأ `sales.total_minor` (إيراد اليوم، الدرج، الإيصال) بتشوف الزيادة
-- تلقائيًا، والمرتجع الكامل بيرجّعها مع الفاتورة، والمرتجع الجزئي بيرجّع قيمة
-- البنود الراجعة بس — الزيادة خدمة اتقدمت بالفعل.
--
-- أضيف فقط: الصفوف القديمة تبدأ من صفر، وإجماليها كما هو.

ALTER TABLE sales
    ADD COLUMN surcharge_minor INTEGER NOT NULL DEFAULT 0 CHECK (surcharge_minor >= 0);
