//! Sessions: the proof of who is operating the shop right now.
//!
//! # Why the fields are private
//!
//! `plan:151` requires that Rust resolves identity and role from the database
//! and never trusts what the frontend sends. `spec:210` requires that this be
//! proven at the application/data layer rather than by hiding UI elements.
//!
//! `Session` therefore has no public constructor and no public fields. The only
//! way to obtain one is [`Session::open`], which lives in this module and
//! validates expiry itself. `commands/` cannot fabricate a verified session: it
//! can only hand persistence facts to this module and receive a `Session` back
//! if those facts are currently valid. A struct literal is a compile error
//! outside this file.

use std::fmt;

use serde::{Deserialize, Serialize};

use crate::domain::identity::DomainError;
use crate::domain::identity::Permission;
use crate::domain::identity::Role;
use crate::domain::identity::UserId;
use super::sensitivity::OwnerApproval;

/// Milliseconds since the Unix epoch, UTC.
///
/// Stored as an integer rather than a formatted string so that SQLite compares
/// and orders timestamps numerically with no format ambiguity, and so no
/// date-formatting dependency is needed on the write path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Timestamp(i64);

impl Timestamp {
    pub fn from_millis(value: i64) -> Self {
        Self(value)
    }

    pub fn as_millis(&self) -> i64 {
        self.0
    }

    /// Current wall-clock time.
    pub fn now() -> Self {
        match std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH) {
            Ok(delta) => Self(delta.as_millis() as i64),
            // Only reachable if the system clock is set before 1970.
            Err(_) => Self(0),
        }
    }

    pub fn plus_millis(&self, delta: i64) -> Self {
        Self(self.0.saturating_add(delta))
    }

    /// Milliseconds elapsed since `earlier`, never negative.
    pub fn millis_since(&self, earlier: Timestamp) -> i64 {
        self.0.saturating_sub(earlier.0).max(0)
    }
}

/// How much the user has proved recently.
///
/// `plan:151` requires re-authentication before wholesale data is revealed.
/// Building the mechanism now, while there is exactly one command family to
/// wire it to, is materially cheaper than retrofitting it across every command
/// once the catalog and sales slices exist.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Assurance {
    /// Proven by logging in.
    Normal,
    /// Proven again after the session was already established.
    Reauthenticated,
}

/// An opaque session secret.
///
/// This value never crosses into JavaScript. It is generated by the service
/// layer, handed to the OS credential store, and only its SHA-256 digest is
/// written to SQLite (ADR-009).
#[derive(Clone, PartialEq, Eq)]
pub struct SessionToken(String);

impl SessionToken {
    pub fn new(bytes: [u8; 32]) -> Self {
        // 32 bytes of CSPRNG output as lowercase hex: 64 characters, 256 bits
        // of entropy, and no base64 alphabet ambiguity when it is read back.
        let mut out = String::with_capacity(64);
        for byte in bytes {
            out.push(char::from_digit(u32::from(byte >> 4), 16).expect("nibble is < 16"));
            out.push(char::from_digit(u32::from(byte & 0x0f), 16).expect("nibble is < 16"));
        }
        Self(out)
    }

    /// Parse a token that was previously produced by `new`.
    pub fn parse(value: &str) -> Option<Self> {
        if value.len() == 64 && value.bytes().all(|b| b.is_ascii_hexdigit()) {
            Some(Self(value.to_ascii_lowercase()))
        } else {
            None
        }
    }

    pub fn expose(&self) -> &str {
        &self.0
    }
}

/// Redacted so a token can never reach a log line by accident.
impl fmt::Debug for SessionToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SessionToken(<redacted>)")
    }
}

impl fmt::Display for SessionToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Persistence facts about a session, as read from SQLite.
///
/// Constructible anywhere; it is data, not authority.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionFacts {
    pub user_id: UserId,
    pub role: Role,
    pub assurance: Assurance,
    pub issued_at: Timestamp,
    pub last_seen_at: Timestamp,
    pub absolute_expires_at: Timestamp,
    /// The account must change its password before doing anything else.
    ///
    /// Read from `user_credentials` on every resolve, never cached on the session
    /// row, for the same reason `role` is not: a manager reset must take effect
    /// on the very next command rather than lingering until the session expires.
    pub must_change_password: bool,
    /// When the account was disabled, or `None` while it is active.
    pub disabled_at: Option<Timestamp>,
    /// The owner approval waiting on this session, or `None` (ADR-017 §3).
    ///
    /// Read from `sessions.approved_by` / `approved_at`. Unlike role and the
    /// disable state it records an event on *this* session, so the session row
    /// is its home. Whether it may still be spent is decided twice: freshness
    /// when the operation is authorized, and one use — by a manager who is
    /// still active — when the operation commits.
    pub owner_approval: Option<OwnerApproval>,
    /// Whether this session stands for a shop that has not claimed an account yet
    /// (`ADR-039`).
    ///
    /// Not a persisted column: the `sessions` table has no such flag, because an
    /// open shop has no session row to put it on. The one place that resolves the
    /// open operator sets it, and it is what lets the two approval axes answer
    /// for a device whose whole proof is "this is the shop's own computer".
    pub open_mode: bool,
}

/// Policy constants, fixed by Product Owner decision on 2026-10-03.
pub const IDLE_TIMEOUT_MS: i64 = 15 * 60 * 1000;
pub const ABSOLUTE_LIFETIME_MS: i64 = 12 * 60 * 60 * 1000;

/// A currently valid session.
///
/// Fields are private on purpose; see the module documentation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Session {
    user_id: UserId,
    role: Role,
    assurance: Assurance,
    issued_at: Timestamp,
    last_seen_at: Timestamp,
    absolute_expires_at: Timestamp,
    must_change_password: bool,
    /// Private with an accessor, exactly as every other session field: a
    /// caller must not be able to declare itself approved.
    owner_approval: Option<OwnerApproval>,
    /// The same rule as `owner_approval`: a session cannot claim to be open by
    /// setting a flag. Only the facts handed to [`Session::open`] decide it, and
    /// those facts are read from the database by a service (`ADR-039`).
    open_mode: bool,
}

impl Session {
    /// Validate persistence facts against the policy and produce a session.
    ///
    /// This is the single entry point. Callers cannot widen the result: if the
    /// facts are stale the only possible return is an error.
    ///
    /// A disabled account yields no session at all. The check lives here rather
    /// than only at login so that disabling an operator stops work immediately,
    /// not whenever their current session happens to expire.
    pub fn open(facts: SessionFacts, now: Timestamp) -> Result<Self, DomainError> {
        if now >= facts.absolute_expires_at {
            return Err(DomainError::SessionAbsoluteExpired);
        }
        // `>=`, matching the absolute deadline. A session idle for exactly the
        // timeout has been idle for the timeout, and two deadlines with
        // different boundary semantics would be a trap for whoever writes the
        // catalog slice next.
        if now.millis_since(facts.last_seen_at) >= IDLE_TIMEOUT_MS {
            return Err(DomainError::SessionIdleExpired);
        }
        if facts.disabled_at.is_some() {
            return Err(DomainError::AccountDisabled);
        }

        Ok(Self {
            user_id: facts.user_id,
            role: facts.role,
            assurance: facts.assurance,
            issued_at: facts.issued_at,
            last_seen_at: facts.last_seen_at,
            absolute_expires_at: facts.absolute_expires_at,
            must_change_password: facts.must_change_password,
            owner_approval: facts.owner_approval,
            open_mode: facts.open_mode,
        })
    }

    /// Whether this session is the open operator of a shop that has not claimed
    /// an account yet (`ADR-039`).
    ///
    /// Read-only, like every other session fact: it is answered from the row a
    /// service read, never from a flag a caller can raise.
    pub fn is_open_mode(&self) -> bool {
        self.open_mode
    }

    pub fn user_id(&self) -> UserId {
        self.user_id
    }

    pub fn role(&self) -> Role {
        self.role
    }

    pub fn assurance(&self) -> Assurance {
        self.assurance
    }

    pub fn issued_at(&self) -> Timestamp {
        self.issued_at
    }

    pub fn last_seen_at(&self) -> Timestamp {
        self.last_seen_at
    }

    pub fn absolute_expires_at(&self) -> Timestamp {
        self.absolute_expires_at
    }

    /// Idle timer restart, after a command has been authorised.
    ///
    /// The absolute deadline is untouched, so idling can never extend a
    /// session past twelve hours.
    pub fn touch(&mut self, now: Timestamp) {
        self.last_seen_at = now;
    }

    /// Promote this session to `Reauthenticated` after the user re-proves
    /// their password.
    pub fn upgrade_assurance(&mut self) {
        self.assurance = Assurance::Reauthenticated;
    }

    /// Return this session to `Normal` after a self-service operation completes.
    ///
    /// `Reauthenticated` means "this password was freshly proven", which is a
    /// property of a moment, not a lasting state. Leaving a session upgraded
    /// after its owner changed their own password would let the elevated
    /// assurance leak into unrelated later commands, so it is deliberately
    /// dropped again.
    pub fn downgrade_assurance(&mut self) {
        self.assurance = Assurance::Normal;
    }

    /// The owner approval waiting on this session, or `None`.
    ///
    /// Read-only on purpose: an approval is stamped by the approval service and
    /// spent by the operation's transaction, both in the database, never by
    /// mutating a `Session` value that could outlive the row it was read from.
    pub fn owner_approval(&self) -> Option<OwnerApproval> {
        self.owner_approval
    }

    /// Whether the owner still owes a forced password change.
    pub fn must_change_password(&self) -> bool {
        self.must_change_password
    }

    /// Clear the forced-change flag, once the password has been changed.
    pub fn clear_must_change_password(&mut self) {
        self.must_change_password = false;
    }

    /// The single authorisation decision.
    ///
    /// Three axes, consulted in order:
    ///
    /// 1. A forced password change narrows the session to that one operation.
    ///    Checked first because it is the most specific state: a sales user in
    ///    this state must still be refused `Sell`, and a manager refused
    ///    `ManageUsers`, while `ChangeOwnPassword` remains available.
    /// 2. Role. A sales user never holds `ViewCostAndProfit` (`spec:54`) or
    ///    `ManageUsers`.
    /// 3. Assurance. Even a manager needs `Reauthenticated` before wholesale
    ///    figures (`plan:151`) or user administration are released.
    ///
    /// `spec:210` requires this decision at the application/data layer, which is
    /// why it lives here and not in the frontend. The fourth axis — the owner's
    /// PIN approval for sensitive operations — is deliberately separate, in
    /// [`Session::require_sensitivity`], because inventory work is a mix of
    /// routine and sensitive (ADR-017 §3).
    pub fn authorize(&self, permission: Permission) -> Result<(), DomainError> {
        if self.must_change_password && permission != Permission::ChangeOwnPassword {
            return Err(DomainError::PasswordChangeRequired);
        }
        if !self.role.allows(permission) {
            return Err(DomainError::PermissionDenied);
        }
        if permission.requires_reauthenticated() && self.assurance != Assurance::Reauthenticated {
            return Err(DomainError::ReauthenticationRequired);
        }
        Ok(())
    }
}