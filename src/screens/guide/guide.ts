/** Filter guide topics by category tab and Arabic/English search query. */
export function filterGuideTopics(
  topics: readonly GuideTopic[],
  category: GuideCategoryId,
  rawQuery: string,
): GuideTopic[] {
  const q = rawQuery.trim().toLowerCase();
  return topics.filter((topic) => {
    if (category !== 'all' && topic.category !== category) {
      return false;
    }
    if (!q) return true;
    const haystack = [
      topic.title,
      topic.summary,
      ...topic.bullets,
      ...topic.keywords,
    ]
      .join(' ')
      .toLowerCase();
    return q.split(/\s+/).every((word) => haystack.includes(word));
  });
}

/** Filter keyboard shortcuts by search query. */
export function filterGuideShortcuts(
  shortcuts: readonly GuideShortcutRow[],
  rawQuery: string,
): GuideShortcutRow[] {
  const q = rawQuery.trim().toLowerCase();
  if (!q) return [...shortcuts];
  return shortcuts.filter((row) => {
    const haystack = `${row.key} ${row.action} ${row.where}`.toLowerCase();
    return q.split(/\s+/).every((word) => haystack.includes(word));
  });
}
